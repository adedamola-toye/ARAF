/**
 * Retail offer and contract generation. Only from an ACTIVE template that the bank has approved for the
 * product and structure, and only from the final assessment snapshot the credit approval was based on.
 * Insurance responsibility is printed exactly as configured for the structure.
 */
import type { Tx } from "../db";
import type { Ctx } from "../context";
import { audit } from "../audit";
import { forbidden, gate } from "../errors";
import { formatKobo } from "../money";
import { formatDateOnly, lagosDate } from "../time";
import { holdsRole } from "./access";
import { storeGeneratedDocument } from "./documents";
import { escapeHtml } from "./offer";
import { approvedRetailAssessment } from "./retail";
import { configGaps, effectiveConfig, gapsBlocking, STRUCTURE_LABELS, type StructureCode } from "./products";
import { computeAffordability, type AffordabilityInput, type AffordabilityOutput, type AssessmentRules } from "./affordability";
import { retailDataSchema } from "./retail-data";
import type { BeneficiarySnapshot } from "./vendors";
import { PLATFORM_NAME } from "../brand";

export const RETAIL_PLACEHOLDERS = [
  "product", "ref", "offer_date", "customer_name", "customer_address", "structure", "principal", "rate", "tenor", "total_payable",
  "monthly_repayment", "insurance_responsibility", "vendor_name", "beneficiary_bank", "beneficiary_account", "beneficiary_account_name",
  "schedule", "assessment_id", "config_version",
];

export async function retailTemplate(q: Tx, productCode: string, structure: string | null) {
  return (
    await q.query(
      `SELECT * FROM offer_templates WHERE status = 'ACTIVE' AND product_code = $1 AND (structure = $2 OR structure IS NULL) ORDER BY structure NULLS LAST LIMIT 1`,
      [productCode, structure],
    )
  ).rows[0] ?? null;
}

// eslint-disable-next-line @typescript-eslint/no-explicit-any
export async function generateRetailOffer(tx: Tx, ctx: Ctx, app: Record<string, any>) {
  const actor = ctx.actor!;
  const task = (await tx.query("SELECT * FROM tasks WHERE application_id = $1 AND status = 'OPEN'", [app.id])).rows[0];
  if (!task || task.stage !== "OFFER_PREPARATION" || task.assignee_id !== actor.staffId || !(await holdsRole(tx, actor.staffId, task.assignee_role))) {
    throw forbidden("The offer can only be generated by the initiator at offer preparation.");
  }
  const cfg = await effectiveConfig(tx, app.product_code, ctx.now);
  if (!cfg) throw gate("No approved product configuration.");
  const blocking = [...gapsBlocking(configGaps(cfg.config, { profile: app.customer_profile, structure: app.financing_structure }), "OFFER"), ...gapsBlocking(configGaps(cfg.config, { profile: app.customer_profile, structure: app.financing_structure }), "FINAL_ASSESSMENT")];
  if (blocking.length) throw gate(`Offer generation is blocked until configured: ${blocking.map((g) => g.label).join("; ")}.`);
  const tpl = await retailTemplate(tx, app.product_code, app.financing_structure);
  if (!tpl) throw gate(`No active offer template exists for ${app.product_label} (${app.financing_structure}).`);
  if (!tpl.production_approved) throw gate(`The ${tpl.name} template (v${tpl.version}) has not been approved by the bank. Offers are generated only from approved templates.`);
  const approved = await approvedRetailAssessment(tx, app.id);
  if (!approved) throw gate("No approved final assessment is on record.");
  const out = approved.outputs as AffordabilityOutput;
  const recomputed = computeAffordability(approved.rules as AssessmentRules, approved.inputs as AffordabilityInput);
  if (recomputed.totalPayableKobo !== out.totalPayableKobo) throw gate("The assessment snapshot could not be reproduced; generation stopped.");
  const version = (await tx.query("SELECT data FROM application_versions WHERE id = $1", [app.current_version_id])).rows[0];
  const data = retailDataSchema.parse(version.data);
  const ben = (version.data.beneficiarySnapshot ?? null) as BeneficiarySnapshot | null;
  const inputs = approved.inputs as AffordabilityInput;
  const values: Record<string, string> = {
    product: app.product_label,
    ref: app.ref,
    offer_date: formatDateOnly(lagosDate(ctx.now)),
    customer_name: app.customer_name ?? "",
    customer_address: data.businessAddress,
    structure: STRUCTURE_LABELS[app.financing_structure as StructureCode] ?? app.financing_structure,
    principal: formatKobo(Number(inputs.principalKobo)),
    rate: out.rateLabel ?? "",
    tenor: String(inputs.tenorMonths),
    total_payable: formatKobo(out.totalPayableKobo),
    monthly_repayment: out.proposedMonthlyDisplay ?? "",
    insurance_responsibility: out.insurance ?? "",
    vendor_name: ben?.vendorName ?? "",
    beneficiary_bank: ben?.institutionName ?? "",
    beneficiary_account: ben?.accountNumber ?? "",
    beneficiary_account_name: ben?.accountName ?? "",
    schedule: out.schedule.length ? `${out.schedule.length} monthly instalments of ${formatKobo(out.schedule[0].amountKobo)}${out.schedule.at(-1)!.amountKobo !== out.schedule[0].amountKobo ? ` (final ${formatKobo(out.schedule.at(-1)!.amountKobo)})` : ""}` : "",
    assessment_id: approved.id,
    config_version: String((approved.rules as AssessmentRules).configVersion),
  };
  const html = String(tpl.body_html).replace(/\{\{([a-z_]+)\}\}/g, (m: string, k: string) => (k in values ? escapeHtml(values[k]) : m));
  const doc = `<!doctype html><html><head><meta charset="utf-8"><title>Offer ${escapeHtml(app.ref)}</title>
<style>body{font-family:Georgia,serif;max-width:800px;margin:24px auto;padding:0 16px;color:#111;line-height:1.5}table{border-collapse:collapse}th,td{text-align:left;padding:4px 12px 4px 0;vertical-align:top}</style></head>
<body><p style="font:600 12px sans-serif;color:#555">${escapeHtml(PLATFORM_NAME)}</p>${html}</body></html>`;
  const main = await storeGeneratedDocument(tx, ctx, {
    appId: app.id,
    category: "GENERATED_OFFER",
    filename: `Offer-${app.ref}-${String(app.financing_structure).toLowerCase()}-t${tpl.version}.html`,
    mime: "text/html",
    data: Buffer.from(doc, "utf8"),
    templateId: tpl.id,
    templateVersion: tpl.version,
    role: task.assignee_role,
    stage: app.stage,
    versionId: app.current_version_id,
  });
  await tx.query("UPDATE applications SET offer_template_id = $2, updated_at = $3 WHERE id = $1", [app.id, tpl.id, ctx.now]);
  await audit(tx, ctx, { action: "OFFER_GENERATED", actorRole: task.assignee_role, applicationId: app.id, stage: app.stage, documentId: main.id, documentVersion: main.version, details: { templateId: tpl.id, templateVersion: tpl.version, product: app.product_code, structure: app.financing_structure, retailAssessmentId: approved.id, insurance: out.insurance } });
  return { documentId: main.id, pdfDocumentId: null, templateVersion: tpl.version as number, format: "HTML" };
}
