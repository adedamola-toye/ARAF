import Link from "next/link";
import { requireUser } from "../../_lib/auth";
import { db } from "@/server/db";
import { offerTracker, OFFER_STATUS_LABEL, type OfferStatus } from "@/server/domain/offer-tracker";
import { STAGE_LABELS, type Stage } from "@/server/domain/stages";
import { formatDuration, formatLagos } from "@/server/time";
import { Money } from "@/components/Money";
import { PageHeader } from "@/components/PageHeader";

export const metadata = { title: "Offer letters" };

const BADGE: Record<OfferStatus, string> = { PREPARING: "badge-blue", AWAITING_ACCEPTANCE: "badge-warn", ACCEPTED: "badge-green" };

/** Originator view of offers generated from approved terms and their signed acceptance. */
export default async function Offers() {
  const { session } = await requireUser();
  const rows = await offerTracker(db, session.staffId);
  const now = Date.now();
  const awaiting = rows.filter((r) => r.status === "AWAITING_ACCEPTANCE");
  const awaitingKobo = awaiting.reduce((t, r) => t + BigInt(r.amount_kobo), 0n).toString();
  return (
    <>
      <PageHeader
        eyebrow="Applications"
        title="Offer letters"
        intro="Offers are generated by ARAF from the approved terms, so they always match the approval. Upload the customer's signed acceptance on the request; disbursement cannot proceed without it."
      />
      <section className="grid-3" style={{ marginBottom: "var(--space-6)" }} aria-label="Offer figures">
        <Money size="hero" label="Awaiting signed acceptance" kobo={awaitingKobo} private hint={`${awaiting.length} offer${awaiting.length === 1 ? "" : "s"}`} />
        <div className="fig fig-lg">
          <span className="fig-label">Being generated</span>
          <span className="fig-value">{rows.filter((r) => r.status === "PREPARING").length}</span>
        </div>
        <div className="fig fig-lg">
          <span className="fig-label">Accepted, in closing</span>
          <span className="fig-value">{rows.filter((r) => r.status === "ACCEPTED").length}</span>
        </div>
      </section>
      {rows.length ? (
        <div className="table-wrap">
          <table className="data responsive">
            <thead>
              <tr>
                <th>Customer</th>
                <th className="num">Amount</th>
                <th>Offer</th>
                <th>Acceptance</th>
                <th>Now at</th>
                <th aria-label="Actions" />
              </tr>
            </thead>
            <tbody>
              {rows.map((r) => (
                <tr key={r.application_id}>
                  <td data-label="Customer">
                    <strong>{r.customer_name ?? r.ref}</strong>
                    <div className="small muted">
                      {r.ref} · {r.product_label ?? "WakeelBoost"}
                    </div>
                  </td>
                  <td className="num" data-label="Amount">
                    <Money size="table" as="span" kobo={r.amount_kobo} private />
                  </td>
                  <td data-label="Offer" className="small">
                    {r.offer_at ? `Generated ${formatLagos(r.offer_at)}` : r.approved_at ? `Approved ${formatLagos(r.approved_at)}` : "—"}
                  </td>
                  <td data-label="Acceptance">
                    <span className={`badge ${BADGE[r.status]}`}>{OFFER_STATUS_LABEL[r.status]}</span>
                    <div className="small muted">{r.signed_at ? `Signed copy uploaded ${formatLagos(r.signed_at)}` : r.offer_at ? `Outstanding ${formatDuration(now - new Date(r.offer_at).getTime())}` : ""}</div>
                  </td>
                  <td data-label="Now at" className="small">
                    {STAGE_LABELS[r.stage as Stage]}
                  </td>
                  <td>
                    <div className="row">
                      {r.offer_doc_id && (
                        <Link className="btn btn-sm btn-ghost" href={`/requests/${r.application_id}?tab=documents&doc=${r.offer_doc_id}`}>
                          Preview
                        </Link>
                      )}
                      {r.mine && r.stage === "OFFER_PREPARATION" && (
                        <Link className="btn btn-sm" href={`/requests/${r.application_id}?task=${r.task_id}`}>
                          {r.signed_doc_id ? "Submit pack" : "Upload signed offer"}
                        </Link>
                      )}
                    </div>
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      ) : (
        <p className="muted">No offers outstanding. Offers appear here once a facility you originated receives final approval.</p>
      )}
    </>
  );
}
